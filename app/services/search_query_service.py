from app.services.llm_service import generate_answer


def generate_search_query(question: str) -> str:
    prompt = f"""
あなたは社内文書検索用の検索クエリ生成AIです。

ユーザーの質問を、社内文書をベクトル検索するための
具体的な検索クエリに変換してください。

ルール:
- 回答そのものは生成しない
- 日本語で検索クエリだけを返す
- 15〜30個程度の単語を使って、具体的な検索クエリを作る
- ユーザーの質問に含まれる人名や固有名詞はできるだけ残す
- 「自己PR」「職歴」「学歴」「資格」など、文書内の見出しになりそうな語を残す
- 質問の内容から、文書に書かれていそうな具体的な専門用語や業務内容を補う
- 資格名、製品名、技術名、研究開発、製品設計などの具体的な語を優先する
- 抽象的な言葉だけで検索しない
- 推測しすぎて、質問と無関係な情報を追加しない
- 不要な説明、文章、箇条書き、記号は付けない
- 検索キーワードをスペースで区切って返す

例:
質問:
小竹さんの自己PRを教えてください

検索クエリ:
小竹晃一 自己PR 研究開発 製品設計 次世代光ディスク CMOSイメージセンサ Velilog-HDL 設計 検証 離職後 基本情報技術者 プログラミング 技術 新しい分野 貢献

ユーザーの質問:
{question}
"""

    return generate_answer(prompt=prompt).strip()
